/// The result type of typed module methods.
pub type Result<T, E = SecopError> = std::result::Result<T, E>;

/// A boxed future of a typed module's method.
pub type BoxFuture<'a, T> = Pin<Box<dyn Future<Output = T> + Send + 'a>>;

/// The behaviour of a typed module, generated by `#[must_server::methods]` from the
/// module's `read_<p>`, `write_<p>`, `do_<c>`, `start` and `poll` methods.
#[diagnostic::on_unimplemented(
    message = "`{Self}` needs a `#[must_server::methods]` impl block",
    label = "no `#[must_server::methods]` impl block for this module type",
    note = "put the module's read_/write_/do_ methods in an impl block annotated with `#[must_server::methods]`, even if it is empty"
)]
pub trait Methods: Send + 'static {
    /// The parameters with a read method.
    const READ: &'static [&'static str];
    /// The parameters with a write method.
    const WRITE: &'static [&'static str];
    /// Whether the module has a poll hook.
    const HAS_POLL: bool = false;

    /// Calls the read method of `parameter`, or `None` if it has none.
    fn read_param<'a>(
        &'a mut self,
        parameter: &str,
        info: &DataInfo,
    ) -> Option<BoxFuture<'a, Result<Value>>>;

    /// Calls the write method of `parameter`, or `None` if it has none.
    fn write_param<'a>(
        &'a mut self,
        parameter: &str,
        value: Value,
        info: &DataInfo,
    ) -> Option<BoxFuture<'a, Result<Value>>>;

    /// Calls the method of `command`.
    fn call_command<'a>(
        &'a mut self,
        command: &str,
        argument: Option<Value>,
        argument_info: Option<&DataInfo>,
        result_info: Option<&DataInfo>,
    ) -> BoxFuture<'a, Result<Option<Value>>>;

    /// Runs the start hook.
    fn start_hook(&mut self) -> BoxFuture<'_, Result<()>> {
        Box::pin(async { Ok(()) })
    }

    /// Runs the poll hook with the parameters due.
    fn poll_hook<'a>(&'a mut self, due: &'a [&'a str]) -> BoxFuture<'a, Result<()>> {
        let _ = due;
        Box::pin(async { Ok(()) })
    }
}

/// Whether `list` (one of the [`Methods`] lists) contains `name`.
pub const fn has(list: &[&str], name: &str) -> bool {
    let mut i = 0;
    while i < list.len() {
        if eq(list[i].as_bytes(), name.as_bytes()) {
            return true;
        }
        i += 1;
    }
    false
}

const fn eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

/// A module type declared with `#[must_server::module]`: its accessibles, properties
/// and state, built from settings.
pub trait TypedModule: Methods + Sized {
    /// The description of the module type, used when a module gets none of its own.
    const DEFAULT_DESCRIPTION: Option<&'static str>;

    /// Constructs a module named `name` from `settings`, with its declaration.
    fn declare(
        name: &str,
        description: &str,
        settings: &mut dyn Settings,
    ) -> Result<Declared<Self>, SettingsErrors>;

    /// The module's parameters, in declaration order.
    fn params(&self) -> Vec<&dyn AnyParam>;
}

/// A constructed typed module: the instance, its declaration, and the configured values
/// to write when the node starts.
pub struct Declared<X> {
    /// The module type's value.
    pub instance: X,
    /// The declaration, without a handler.
    pub module: Module,
    /// Datainfos of the parameters.
    pub params: HashMap<String, DataInfo>,
    /// Argument and result datainfos of the commands.
    pub commands: HashMap<String, (Option<DataInfo>, Option<DataInfo>)>,
    /// Configured values of parameters with a write method, written at start.
    pub initial_writes: Vec<(String, Value)>,
}

/// Constructs the typed module `X` named `name` from `settings` and returns it as a
/// [`Module`] to add to a node. `description` overrides the module type's default.
///
/// ```ignore
/// let t = typed::module::<TemperatureLoop>("T", Some("sample temperature"), json!({"channel": "A"}))?;
/// ```
pub fn module<X: TypedModule>(
    name: &str,
    description: Option<&str>,
    mut settings: impl Settings,
) -> Result<Module, SettingsErrors> {
    let Some(description) = description.or(X::DEFAULT_DESCRIPTION) else {
        let mut error = settings.error(None, "the module needs a description".into());
        name.clone_into(&mut error.module);
        return Err(SettingsErrors(vec![error]));
    };
    let declared = X::declare(name, description, &mut settings)?;
    Ok(declared.module.handler(TypedHandler {
        module: tokio::sync::Mutex::new(declared.instance),
        params: declared.params,
        commands: declared.commands,
        initial_writes: Mutex::new(declared.initial_writes),
    }))
}

/// A parameter declaration, as the module macro writes it.
#[doc(hidden)]
#[must_use]
#[allow(clippy::struct_excessive_bools)]
pub struct ParamSpec<T> {
    name: &'static str,
    description: &'static str,
    datainfo: Result<DataInfo, String>,
    writable: bool,
    constant: Option<T>,
    default: Option<T>,
    group: Option<String>,
    visibility: Option<String>,
    checkable: bool,
    poll_interval: Option<Duration>,
    custom: Vec<(&'static str, Json)>,
    has_read: bool,
    has_write: bool,
}

impl<T: SecopType> ParamSpec<T> {
    /// A parameter with its description and datainfo; `has_read` and `has_write` say
    /// whether the module has read and write methods for it.
    pub fn new(
        name: &'static str,
        description: &'static str,
        datainfo: Result<DataInfo, String>,
        has_read: bool,
        has_write: bool,
    ) -> Self {
        Self {
            name,
            description,
            datainfo,
            writable: false,
            constant: None,
            default: None,
            group: None,
            visibility: None,
            checkable: false,
            poll_interval: None,
            custom: Vec::new(),
            has_read,
            has_write,
        }
    }
    /// Writable by clients.
    pub fn writable(mut self) -> Self {
        self.writable = true;
        self
    }
    /// A constant value.
    pub fn constant(mut self, value: T) -> Self {
        self.constant = Some(value);
        self
    }
    /// The value before any other.
    pub fn default(mut self, value: T) -> Self {
        self.default = Some(value);
        self
    }
    /// The `group` property.
    pub fn group(mut self, group: impl Into<String>) -> Self {
        self.group = Some(group.into());
        self
    }
    /// The `visibility` property.
    pub fn visibility(mut self, visibility: impl Into<String>) -> Self {
        self.visibility = Some(visibility.into());
        self
    }
    /// `checkable: true`.
    pub fn checkable(mut self) -> Self {
        self.checkable = true;
        self
    }
    /// A poll interval of its own.
    pub fn poll_interval(mut self, interval: Duration) -> Self {
        self.poll_interval = Some(interval);
        self
    }
    /// A custom property.
    pub fn custom(mut self, key: &'static str, value: impl Into<Json>) -> Self {
        self.custom.push((key, value.into()));
        self
    }
}

/// A command declaration, as the module macro writes it.
#[doc(hidden)]
#[must_use]
pub struct CommandSpec {
    name: &'static str,
    description: &'static str,
    argument: Option<Result<DataInfo, String>>,
    result: Option<Result<DataInfo, String>>,
    group: Option<String>,
    visibility: Option<String>,
    checkable: bool,
    custom: Vec<(&'static str, Json)>,
    /// Problems with the Rust types of the argument and result.
    problems: Vec<String>,
}

impl CommandSpec {
    /// A command with its description.
    pub fn new(name: &'static str, description: &'static str) -> Self {
        Self {
            name,
            description,
            argument: None,
            result: None,
            group: None,
            visibility: None,
            checkable: false,
            custom: Vec::new(),
            problems: Vec::new(),
        }
    }
    /// The argument's datainfo, held as `T`.
    pub fn argument<T: SecopType>(mut self, info: Result<DataInfo, String>) -> Self {
        self.problems.extend(check_type::<T>(&info, "argument"));
        self.argument = Some(info);
        self
    }
    /// The result's datainfo, held as `T`.
    pub fn result<T: SecopType>(mut self, info: Result<DataInfo, String>) -> Self {
        self.problems.extend(check_type::<T>(&info, "result"));
        self.result = Some(info);
        self
    }
    /// The `group` property.
    pub fn group(mut self, group: impl Into<String>) -> Self {
        self.group = Some(group.into());
        self
    }
    /// The `visibility` property.
    pub fn visibility(mut self, visibility: impl Into<String>) -> Self {
        self.visibility = Some(visibility.into());
        self
    }
    /// `checkable: true`.
    pub fn checkable(mut self) -> Self {
        self.checkable = true;
        self
    }
    /// A custom property.
    pub fn custom(mut self, key: &'static str, value: impl Into<Json>) -> Self {
        self.custom.push((key, value.into()));
        self
    }
}

/// Whether a built datainfo fits the Rust type `T`.
fn check_type<T: SecopType>(info: &Result<DataInfo, String>, what: &str) -> Option<String> {
    let info = info.as_ref().ok()?;
    match Kind::of(info) {
        Some(kind) if accepts(T::KINDS, kind) => {
            T::fits(info).err().map(|e| format!("{what}: {e}"))
        }
        _ => Some(format!(
            "{what}: the datainfo {} does not fit the Rust type `{}`",
            info.to_json(),
            std::any::type_name::<T>()
        )),
    }
}

/// Collects a typed module's declaration and the problems found on the way, for the
/// code the module macro generates.
#[doc(hidden)]
pub struct Declaring<'s> {
    name: String,
    settings: &'s mut dyn Settings,
    errors: Vec<SettingsError>,
    module: Option<Module>,
    params: HashMap<String, DataInfo>,
    commands: HashMap<String, (Option<DataInfo>, Option<DataInfo>)>,
    initial_writes: Vec<(String, Value)>,
}

impl<'s> Declaring<'s> {
    /// Starts declaring the module `name`.
    pub fn new(
        name: &str,
        description: &str,
        interface_classes: &[&str],
        settings: &'s mut dyn Settings,
    ) -> Self {
        Self {
            name: name.to_owned(),
            settings,
            errors: Vec::new(),
            module: Some(
                Module::new(name, description).interface_classes(interface_classes.iter().copied()),
            ),
            params: HashMap::new(),
            commands: HashMap::new(),
            initial_writes: Vec::new(),
        }
    }

    fn error(&mut self, key: Option<&str>, message: String) {
        let mut error = self.settings.error(key, message);
        error.module.clone_from(&self.name);
        self.errors.push(error);
    }

    /// Checks a setting against `info` with all limits.
    fn decode(&mut self, key: &str, json: &Json, info: &DataInfo) -> Option<Value> {
        match info.decode(json, Mode::Request) {
            Ok(value) => Some(value),
            Err(e) => {
                self.error(Some(key), SecopError::from(e).message);
                None
            }
        }
    }

    /// Takes the property `key`: its setting, else `default`, else an error. The value
    /// returned on an error only lets the construction go on to find more problems.
    pub fn property<T: SecopType>(
        &mut self,
        key: &'static str,
        info: Result<DataInfo, String>,
        default: Option<T>,
    ) -> T {
        let info = match info {
            Ok(info) => info,
            Err(problem) => {
                self.error(Some(key), format!("invalid datainfo: {problem}"));
                return default.unwrap_or_else(T::fallback);
            }
        };
        if let Some(problem) = check_type::<T>(&Ok(info.clone()), "datainfo") {
            self.error(Some(key), problem);
        }
        let Some(json) = self.settings.take(key) else {
            return default.unwrap_or_else(|| {
                self.error(Some(key), format!("the property `{key}` is missing"));
                T::fallback()
            });
        };
        self.decode(key, &json, &info)
            .and_then(|value| match T::from_value(&value, &info) {
                Ok(v) => Some(v),
                Err(e) => {
                    self.error(Some(key), e.message);
                    None
                }
            })
            .unwrap_or_else(T::fallback)
    }

    /// Declares a parameter and returns its field.
    pub fn param<T: SecopType>(&mut self, spec: ParamSpec<T>) -> Param<T> {
        let name = spec.name;
        let info = match spec.datainfo {
            Ok(info) => info,
            Err(problem) => {
                self.error(Some(name), format!("invalid datainfo: {problem}"));
                return Param::new(name, placeholder(), T::fallback());
            }
        };
        if let Some(problem) = check_type::<T>(&Ok(info.clone()), "datainfo") {
            self.error(Some(name), problem);
            return Param::new(name, info, T::fallback());
        }
        let encode = |v: &T| v.to_value(&info);
        let mut initial = spec.default.clone();
        let mut configured = None;
        if let Some(json) = self.settings.take(name) {
            if spec.constant.is_some() {
                self.error(
                    Some(name),
                    format!("`{name}` is constant and cannot be configured"),
                );
            } else if !spec.writable && spec.has_read {
                self.error(
                    Some(name),
                    format!("`{name}` is read from the hardware and cannot be configured"),
                );
            } else if let Some(value) = self.decode(name, &json, &info) {
                match T::from_value(&value, &info) {
                    Ok(v) if spec.writable && spec.has_write => {
                        configured = Some(value).zip(Some(v));
                    }
                    Ok(v) => initial = Some(v),
                    Err(e) => self.error(Some(name), e.message),
                }
            }
        }
        let mut parameter = Parameter::new(name, info.clone(), spec.description);
        if spec.writable {
            parameter = parameter.writable();
        }
        if let Some(constant) = &spec.constant {
            match encode(constant).and_then(|v| info.encode(&v).map_err(SecopError::from)) {
                Ok(json) => parameter = parameter.constant(json),
                Err(e) => self.error(Some(name), format!("constant: {}", e.message)),
            }
        } else if !spec.has_read {
            parameter = parameter.cached();
        }
        let value = initial
            .clone()
            .or_else(|| spec.constant.clone())
            .unwrap_or_else(T::fallback);
        if spec.constant.is_none() && (initial.is_some() || !spec.has_read) {
            match encode(&value) {
                Ok(v) => parameter = parameter.initial_value(v),
                Err(e) => self.error(Some(name), e.message),
            }
        }
        if let Some(group) = &spec.group {
            parameter = parameter.group(group);
        }
        if let Some(visibility) = &spec.visibility {
            parameter = parameter.visibility(visibility);
        }
        if let Some(interval) = spec.poll_interval {
            parameter = parameter.poll_interval(interval);
        }
        let mut props = spec.custom;
        if spec.checkable {
            props.push(("checkable", Json::Bool(true)));
        }
        for (key, json) in props {
            match parameter.property(key, json) {
                Ok(p) => parameter = p,
                Err(e) => {
                    self.error(Some(name), e.to_string());
                    return Param::new(name, info, value);
                }
            }
        }
        if let Some((value, _)) = configured {
            self.initial_writes.push((name.to_owned(), value));
        }
        self.params.insert(name.to_owned(), info.clone());
        if let Some(module) = self.module.take() {
            match module.parameter(parameter) {
                Ok(module) => self.module = Some(module),
                Err(e) => self.error(Some(name), e.to_string()),
            }
        }
        Param::new(name, info, value)
    }

    /// Declares a command.
    pub fn command(&mut self, spec: CommandSpec) {
        let name = spec.name;
        for problem in spec.problems {
            self.error(Some(name), problem);
        }
        let mut infos = (None, None);
        let mut builder = DataInfo::command();
        for (slot, which, info) in [(0, "argument", spec.argument), (1, "result", spec.result)] {
            match info {
                Some(Ok(info)) => {
                    builder = if slot == 0 {
                        builder.argument(&info)
                    } else {
                        builder.result(&info)
                    };
                    if slot == 0 {
                        infos.0 = Some(info);
                    } else {
                        infos.1 = Some(info);
                    }
                }
                Some(Err(problem)) => self.error(Some(name), format!("invalid {which}: {problem}")),
                None => {}
            }
        }
        let info = match builder.build() {
            Ok(info) => info,
            Err(e) => {
                self.error(Some(name), e.to_string());
                return;
            }
        };
        let mut command = ModelCommand::new(name, info, spec.description);
        if let Some(group) = &spec.group {
            command = command.group(group);
        }
        if let Some(visibility) = &spec.visibility {
            command = command.visibility(visibility);
        }
        let mut props = spec.custom;
        if spec.checkable {
            props.push(("checkable", Json::Bool(true)));
        }
        for (key, json) in props {
            match command.property(key, json) {
                Ok(c) => command = c,
                Err(e) => {
                    self.error(Some(name), e.to_string());
                    return;
                }
            }
        }
        self.commands.insert(name.to_owned(), infos);
        if let Some(module) = self.module.take() {
            match module.command(command) {
                Ok(module) => self.module = Some(module),
                Err(e) => self.error(Some(name), e.to_string()),
            }
        }
    }

    /// Ends the declaration: settings not taken are unknown.
    pub fn finish<X>(mut self, instance: X) -> Result<Declared<X>, SettingsErrors> {
        for key in self.settings.remaining() {
            self.error(
                Some(&key),
                format!("unknown setting `{key}`: neither a property nor a parameter"),
            );
        }
        match self.module {
            Some(module) if self.errors.is_empty() => Ok(Declared {
                instance,
                module,
                params: self.params,
                commands: self.commands,
                initial_writes: self.initial_writes,
            }),
            _ => Err(SettingsErrors(self.errors)),
        }
    }
}

/// A datainfo for a parameter whose own one is invalid, to go on finding problems.
fn placeholder() -> DataInfo {
    DataInfo::string().build().expect("a valid datainfo")
}

/// Serves a typed module: one request at a time, with `&mut` access to the module.
pub struct TypedHandler<X> {
    module: tokio::sync::Mutex<X>,
    params: HashMap<String, DataInfo>,
    commands: HashMap<String, (Option<DataInfo>, Option<DataInfo>)>,
    initial_writes: Mutex<Vec<(String, Value)>>,
}

fn no_such(what: &str, name: &str) -> SecopError {
    SecopError::new(
        ErrorClass::InternalError,
        format!("`{name}` is not a {what} of this typed module"),
    )
}

/// Checks the shape of a value a method produced for `parameter`.
fn shaped(parameter: &str, value: Value, info: &DataInfo) -> Result<Value> {
    super::value::check_shape(&value, info).map_err(|e| {
        SecopError::new(
            ErrorClass::InternalError,
            format!("the value of `{parameter}` does not fit its datainfo: {e}"),
        )
    })?;
    Ok(value)
}

fn param_of<'m, X: TypedModule>(module: &'m X, name: &str) -> Option<&'m dyn AnyParam> {
    module.params().into_iter().find(|p| p.name() == name)
}

impl<X: TypedModule> TypedHandler<X> {
    fn info(&self, parameter: &str) -> Result<&DataInfo> {
        self.params
            .get(parameter)
            .ok_or_else(|| no_such("parameter", parameter))
    }

    /// Writes `value` with the write method of `parameter`, or stores it without one.
    async fn write(
        &self,
        module: &mut X,
        ctx: &Ctx,
        parameter: &str,
        value: Value,
    ) -> Result<Value> {
        let info = self.info(parameter)?;
        let written = if has(X::WRITE, parameter) {
            let call = module
                .write_param(parameter, value, info)
                .ok_or_else(|| no_such("writable parameter", parameter))?;
            in_request(ctx.clone(), call).await?
        } else {
            value
        };
        let written = shaped(parameter, written, info)?;
        if let Some(param) = param_of(module, parameter) {
            param.store_value(&written)?;
        }
        Ok(written)
    }
}

#[async_trait]
impl<X: TypedModule> ModuleHandler for TypedHandler<X> {
    fn implementation(&self) -> String {
        std::any::type_name::<X>().to_owned()
    }

    async fn start(&self, ctx: &Ctx) -> Result<()> {
        let mut module = self.module.lock().await;
        let publisher = ctx.publisher();
        for param in module.params() {
            param.bind(&publisher);
        }
        let started = in_request(ctx.clone(), module.start_hook()).await;
        let writes = std::mem::take(
            &mut *self
                .initial_writes
                .lock()
                .unwrap_or_else(PoisonError::into_inner),
        );
        for (parameter, value) in writes {
            match self.write(&mut module, ctx, &parameter, value).await {
                Ok(written) => {
                    let _ = ctx.update(&parameter, written);
                }
                Err(error) => {
                    ctx.log(
                        AppLogLevel::Error,
                        format!("the initial write of `{parameter}` failed: {error}"),
                    );
                    ctx.update_error(&parameter, error);
                }
            }
        }
        started
    }

    async fn read(&self, ctx: &Ctx, parameter: &str) -> HandlerResult {
        let mut module = self.module.lock().await;
        let info = self.info(parameter)?;
        let value = if has(X::READ, parameter) {
            let call = module
                .read_param(parameter, info)
                .ok_or_else(|| no_such("readable parameter", parameter))?;
            in_request(ctx.clone(), call).await?
        } else {
            param_of(&*module, parameter)
                .ok_or_else(|| no_such("parameter", parameter))?
                .current_value()?
        };
        let value = shaped(parameter, value, info)?;
        if let Some(param) = param_of(&*module, parameter) {
            param.store_value(&value)?;
        }
        Ok(Reading::new(value))
    }

    async fn change(&self, ctx: &Ctx, parameter: &str, value: Value) -> HandlerResult {
        let mut module = self.module.lock().await;
        self.write(&mut module, ctx, parameter, value)
            .await
            .map(Reading::new)
    }

    async fn call(&self, ctx: &Ctx, command: &str, argument: Option<Value>) -> CallResult {
        let mut module = self.module.lock().await;
        let (argument_info, result_info) = self
            .commands
            .get(command)
            .ok_or_else(|| no_such("command", command))?;
        let result = in_request(
            ctx.clone(),
            module.call_command(
                command,
                argument,
                argument_info.as_ref(),
                result_info.as_ref(),
            ),
        )
        .await?;
        Ok(result.map(Reading::new))
    }

    async fn poll(&self, ctx: &Ctx, due: &[&str]) {
        if X::HAS_POLL {
            let mut module = self.module.lock().await;
            if let Err(error) = in_request(ctx.clone(), module.poll_hook(due)).await {
                ctx.log(AppLogLevel::Warning, format!("polling failed: {error}"));
            }
        } else {
            // typed modules handle one request at a time: read the due parameters in turn
            for &parameter in due {
                let _ = ctx.read(parameter).await;
            }
        }
    }
}
